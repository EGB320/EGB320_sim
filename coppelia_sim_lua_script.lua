-- EGB320 Search and Rescue Robot Control Script for CoppeliaSim (2026)
-- Maze/wall/post/victim generation is done entirely from Python (warehousebot_lib.py) via
-- the ZeroMQ remote API - this script only resolves the robot handle and keeps a small set
-- of optional legacy (2025 warehouse challenge) helper functions available for callScriptFunction.

sim = require('sim')

-- Global variables
local robotHandle
local leftMotor, rightMotor
local dummyCollectorHandles = {}
local dummySampleHandles = {}
local obstacleHandles = {}
local object_detector
local itemTemplateHandles = {}
local itemNamesLookup = {"BOWL", "MUG", "BOTTLE", "SOCCER_BALL", "RUBIKS_CUBE", "CEREAL_BOX"}
local warehouseItemHandles = {}
local heldItems = {}


-- Utility function for safe object handle retrieval
function safeGetObjectHandle(name, required)
    local handle = sim.getObject(name, {noError = true})
    if handle == -1 then
        local status = required and "Error" or "Warning"
        print(status .. ": Could not find object '" .. name .. "'")
    end
    return handle
end

function sysCall_init()
    print("Initializing EGB320 search and rescue robot script...")

    -- Resolve the robot handle safely; used by the optional distance-check helper below.
    -- The maze (walls/posts/victims) is generated by warehousebot_lib.py, not by this script.
    robotHandle = safeGetObjectHandle("/Robot", true)

    -- Storage used only by the optional legacy (2025 warehouse challenge) helper functions below
    itemTemplateHandles = {}
    warehouseItemHandles = {}
    heldItems = {}

    print("Robot script initialization complete - system ready for operation")
end

function sysCall_actuation()
    -- Minimal by design: robot motion is driven from Python via SetTargetVelocities(),
    -- which sets joint target velocities directly - no per-step actuation logic is needed here.
end

function sysCall_sensing()
    -- Minimal by design: vision sensor handling (camera/object detector) is driven from
    -- Python via sim.handleVisionSensor() remote API calls - no per-step sensing logic is needed here.
end

function sysCall_cleanup()
    print("Cleaning up robot script...")
end

-- Generic distance measurement helper (still used by warehousebot_lib.py-style callers)
getDistanceToObject = function(inInts, inFloats, inStrings, inBuffer)
    local results = {}
    local distanceData = {}
    
    if #inInts == 0 then
        print("Warning: getDistanceToObject called with no target objects")
        return {1}, {}, {}, ''
    end
    
    for i = 1, #inInts do
        local threshold = inFloats[i] or 1.0 -- Default threshold if not provided
        local result, data, handles = sim.checkDistance(robotHandle, inInts[i], threshold)
        
        -- Convert to consistent error code format (0 = success, 1 = failure)
        if result == 1 then 
            result = 0
        else
            result = 1
        end
        
        table.insert(results, result)
        
        -- Safely append distance data
        if data then
            for j = 1, #data do
                table.insert(distanceData, data[j])
            end
        end
    end
    
    return results, distanceData, {}, ''
end

