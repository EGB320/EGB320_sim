-- Legacy (2025 warehouse challenge) bay content helper; unused in the search and rescue phase
SetBayContents = function(inInts, inFloats, inStrings, inBuffer)
    if #inInts < 4 then
        print("Error: SetBayContents requires 4 integer parameters")
        return {1}, {}, {}, ''
    end
    
    local shelf = inInts[1]
    local bayX = inInts[2]
    local bayY = inInts[3]
    local itemTypeEnum = inInts[4]
    
    -- Validate input parameters
    if itemTypeEnum < 1 or itemTypeEnum > #itemNamesLookup then
        print("Error: Invalid item type enum: " .. itemTypeEnum)
        return {1}, {}, {}, ''
    end
    
    if itemTemplateHandles[itemTypeEnum] == -1 then
        print("Error: Template for item type " .. itemNamesLookup[itemTypeEnum] .. " not available")
        return {1}, {}, {}, ''
    end
    
    -- Get bay handle
    local bayPath = "/Shelf" .. shelf .. "/Bay" .. bayX .. bayY
    local bayHandle = sim.getObject(bayPath, {noError = true})
    
    if bayHandle == -1 then
        print("Error: Could not find bay at " .. bayPath)
        return {1}, {}, {}, ''
    end
    
    -- Create or find item
    local itemName = itemNamesLookup[itemTypeEnum] .. shelf .. bayX .. bayY
    local itemHandle = sim.getObject("/" .. itemName, {noError = true})
    
    if itemHandle == -1 then
        local templateHandle = itemTemplateHandles[itemTypeEnum]
        itemHandle = sim.copyPasteObjects({templateHandle}, 0)[1]
        sim.setObjectAlias(itemHandle, itemName)
        print("Created new item: " .. itemName)
    else
        print("Using existing item: " .. itemName)
    end
    
    -- Position item in bay
    __setObjectPosition__(itemHandle, bayHandle, {0, 0, 0})
    table.insert(warehouseItemHandles, itemHandle)
    
    print("Item " .. itemNamesLookup[itemTypeEnum] .. " placed in bay " .. shelf .. "-" .. bayX .. "-" .. bayY)
    return {0}, {}, {}, ''
end

-- Legacy (2025 warehouse challenge) item collection helper; unused in the search and rescue phase
JoinRobotAndItem = function(inInts, inFloats, inStrings, inBuffer)
    if #inInts == 0 then
        print("Warning: JoinRobotAndItem called with no items")
        return {0}, {}, {}, ''
    end
    
    if #dummySampleHandles == 0 then
        print("Error: No sample dummy handles available")
        return {1}, {}, {}, ''
    end
    
    local itemsGrabbed = 0
    for i = 1, #inInts do
        local objectHandle = inInts[i]
        
        -- Validate object handle
        if objectHandle ~= -1 and sim.isHandle(objectHandle) then
            __setObjectPosition__(objectHandle, dummySampleHandles[1], {0, 0, 0.03})
            sim.setObjectParent(objectHandle, dummySampleHandles[1], true)
            table.insert(heldItems, objectHandle)
            itemsGrabbed = itemsGrabbed + 1
            print("Grabbed item with handle: " .. objectHandle)
        else
            print("Warning: Invalid object handle: " .. objectHandle)
        end
    end
    
    print("Robot grabbed " .. itemsGrabbed .. " items")
    return {0}, {}, {}, ''
end

-- Item release function - still called by warehousebot_lib.py's UpdateItem() via callScriptFunction
RobotReleaseItem = function(inInts, inFloats, inStrings, inBuffer)
    if #heldItems == 0 then
        print("Warning: No items to release")
        return {0}, {}, {}, ''
    end
    
    local objectHandle = table.remove(heldItems, 1)
    
    if objectHandle ~= -1 and sim.isHandle(objectHandle) then
        sim.setObjectParent(objectHandle, -1, true)
        sim.setObjectInt32Param(objectHandle, 3004, 1) -- make object respondable
        sim.setObjectInt32Param(objectHandle, sim.shapeintparam_static, 0)
        print("Released item with handle: " .. objectHandle)
        print("Items remaining in robot: " .. #heldItems)
    else
        print("Error: Invalid item handle during release")
    end
    
    return {0}, {}, {}, ''
end

